update public.sous_prefectures
set code_sp = null,
    est_active = false,
    sp_assigned_at = null;

with candidates as (
  select
    sp.id,
    t.cod_sp,
    row_number() over (partition by t.cod_sp order by sp.id) as rn
  from public.sous_prefectures sp
  join public.departements d on d.id = sp.departement_id
  join tmp_anstat_sp t
    on d.code = t.cod_dep
   and lower(sp.nom) = lower(t.nom_sp)
)
update public.sous_prefectures sp
set code_sp = c.cod_sp,
    est_active = true,
    sp_assigned_at = now()
from candidates c
where c.id = sp.id
  and c.rn = 1;

insert into public.sous_prefectures (nom, code, departement_id, est_active, code_sp, sp_assigned_at)
select
  t.nom_sp,
  t.cod_sp,
  d.id,
  true,
  t.cod_sp,
  now()
from tmp_anstat_sp t
join public.departements d on d.code = t.cod_dep
where not exists (
  select 1
  from public.sous_prefectures sp
  where sp.code_sp = t.cod_sp
);

